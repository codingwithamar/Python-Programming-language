def main():
    #----------------------------------------------------------------------------------------------------
    #										'Arithmatic Operators'
    #----------------------------------------------------------------------------------------------------
    a = 10
    b = 3
    c = -4

    print(a - b)   # 7
    print(a * b)   # 30
    print(a / b)   # 3.333... (float division)
    print(a // b)  # 3 (floor/integer division/Round Figure)
    print(a % b)   # 1 (remainder)
    print(a ** b)  # 1000 (power: 10^3)
    #________________________________________________________________________________
    #						'1. Addition / Unary Plus ( + )'
    print(f"A = {a} B = {b} C = {c}")
    print("-----1. Addition(+)-----")
    print("A + B = ", a + b)   # 13
    print("A + C = ", a + c)   # 6      /10 + (-4) = 6
    print("C + A = ", c + a)   # 6      / - 4 + 10 = 6

    #   1 MB = MegaBytes = 1,00,00,000 Bytes (1 KB = 1000 Bytes)
    #   1 MiB = MebiBytes = 1,00,48,576 Bytes (1 KiB = 1024 Bytes)

    total_bytes = 15_728_640  # bytes from a demo log file
    MiB = total_bytes / (1024 ** 2)     #1,57,28,640 / 1,00,48,576 = 1.56
    remaining_KiB = (total_bytes % (1024 ** 2)) // 1024     #1,57,28,640 % 1,00,48,576 = 15.00
    print(f"{MiB=!r} MiB,\n{remaining_KiB=!r} KiB leftover") # MiB=15.0 MiB, remaining_KiB=0 KiB leftover
    #________________________________________________________________________________
    
    #________________________________________________________________________________
    #						'2. Substraction / Unary Minus ( - )'
    print("-----2. Substraction(-)-----")
    print("A - B = ", a - b)   # 7       /10 - 3 = 7
    print("A - C = ", a - c)   # 14      /10 - (-4) = 14
    print("C - A = ", c - a)   # 6       /-4 - 10 = -14  
    #________________________________________________________________________________
    
    #________________________________________________________________________________
    #						'3. Multipliocation ( * )'
    print("-----3. Multiplication(*)-----")
    print("A * B = ", a * b)   # 30       /10 * 3 = 30
    print("A * C = ", a * c)   # -40      /10 * (-4) = -40
    print("C * A = ", c * a)   # -40      /-4 * 10 = -40
    #________________________________________________________________________________
    
    #________________________________________________________________________________
    #						'4. Division ( / )'
    print("-----4. Division(/)-----")
    print("A / B = ", a / b)   # 3.33       /10 / 3 = 3.33
    print("A / C = ", a / c)   # -2.5     /10 / (-4) = -2.5
    print("C / A = ", c / a)   # -0.4      /-4 / 10 = -0.4
    #________________________________________________________________________________
    
    #________________________________________________________________________________
    #						'5. Floor Division ( // )'
    print("-----5. Floor Division(//)-----")
    print("A // B = ", a // b)   # 3       /10 / 3 = 3
    print("A // C = ", a // c)   # -3     /10 / (-4) = -3
    print("C // A = ", c // a)   # -1      /-4 / 10 = -1
    #________________________________________________________________________________

    #________________________________________________________________________________
    #						'6. Modulus ( % )'
    print("-----6. Modulus(%)-----")
    print("A % B = ", a % b)   #  1     /10 % 3 = 1
    print("A % C = ", a % c)   # -2     /10 % (-4) = -2
    print("C % A = ", c % a)   #  6     /-4 % 10 = 6 
    #________________________________________________________________________________

    #________________________________________________________________________________
    #						'7. Power ( ** )'
    print("-----7. Power(**)-----")
    print("A ** B = ", a ** b)   #       /10 ** 3 = 1000
    print("A ** C = ", a ** c)   #      /10 ** (-4) = 0.0001
    print("C ** A = ", c ** a)   #       /-4 ** 10 = 1048576 
    # Here,
    #(-4) ** 10 = -(4 ** 10) = -1048576
    #((-4) ** 10) = 1048576
    #________________________________________________________________________________

if __name__ == "__main__":
    main()